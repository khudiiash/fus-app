/** @param {string} q @param {string[]} opts texts in order А..Г @param {number} correctIdx 0..3 */
function mcq(q, opts, correctIdx, topic, gradeMin, gradeMax) {
  if (opts.length !== 4) throw new Error('need 4 options')
  return {
    question: q,
    answers: LETTERS.map((letter, i) => ({ letter, text: opts[i] })),
    correctLetter: LETTERS[correctIdx],
    topic,
    gradeMin,
    gradeMax,
  }
}

/** @type {ReturnType<typeof mcq>[]} */
const items = []

let id = 0
function push(...args) {
  items.push({ id: ++id, ...mcq(...args) })
}

